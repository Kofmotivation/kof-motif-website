const initListSlideshow = () => {
  listSlideCleanups.forEach((fn) => fn());
  listSlideCleanups = [];
  listSlideStops = [];
  if (!mosaic || isMobileUi) return;

  mosaic.querySelectorAll(".mosaic-open").forEach((btn) => {
    const inner = btn.querySelector(".mosaic-tilt-inner");
    const imgA = btn.querySelector(".mosaic-tilt-img--a");
    const imgB = btn.querySelector(".mosaic-tilt-img--b");
    const collection = COLLECTIONS[Number(btn.dataset.collection)];
    if (!inner || !imgA || !imgB || !collection?.images?.length) return;

    const frames = collection.images.map((frame) => frame.src).filter(Boolean);
    const cover = collection.cover || frames[0];
    let slide = 0;
    let showingB = false;
    let timer = 0;
    let active = false;

    const ensureB = (src) => {
      if (imgB.dataset.src) {
        imgB.src = imgB.dataset.src;
        delete imgB.dataset.src;
      }
      if (src) imgB.src = src;
    };

    const paintFrame = (src, { instant = false } = {}) => {
      if (instant || reduceMotion || frames.length < 2) {
        imgA.src = src;
        if (imgB.src) {
          imgB.removeAttribute("src");
          imgB.dataset.src = cover;
        }
        inner.classList.remove("is-showing-b");
        showingB = false;
        return;
      }
      if (showingB) {
        imgA.src = src;
        inner.classList.remove("is-showing-b");
        showingB = false;
      } else {
        ensureB(src);
        inner.classList.add("is-showing-b");
        showingB = true;
      }
    };

    const stop = () => {
      active = false;
      btn.classList.remove("is-list-sliding");
      window.clearTimeout(timer);
      timer = 0;
      slide = 0;
      paintFrame(cover, { instant: true });
    };

    const tick = () => {
      if (!active || layoutMode !== "list" || activeView !== "work") {
        stop();
        return;
      }
      slide = (slide + 1) % frames.length;
      paintFrame(frames[slide]);
      preloadListStill(frames[(slide + 1) % frames.length]);
      timer = window.setTimeout(tick, LIST_SLIDE_MS);
    };

    const start = () => {
      if (layoutMode !== "list" || activeView !== "work" || frames.length < 2 || reduceMotion) return;
      active = true;
      btn.classList.add("is-list-sliding");
      slide = 0;
      paintFrame(frames[0], { instant: true });
      preloadListStill(frames[1] || frames[0]);
      window.clearTimeout(timer);
      timer = window.setTimeout(tick, LIST_SLIDE_MS);
    };

    btn.addEventListener("pointerenter", start);
    btn.addEventListener("pointerleave", stop);
    btn.addEventListener("focus", start);
    btn.addEventListener("blur", stop);
    listSlideStops.push(stop);

    listSlideCleanups.push(() => {
      btn.removeEventListener("pointerenter", start);
      btn.removeEventListener("pointerleave", stop);
      btn.removeEventListener("focus", start);
      btn.removeEventListener("blur", stop);
      stop();
    });
  });
};

