const runLoader = () => {
  buildLoaderStrip();
  renderWork();
  document.body.dataset.activeView = "work";

  if (reduceMotion) {
    finishLoader();
    return;
  }

  // Same countdown loader on desktop and mobile
  const images = [
    ...document.querySelectorAll(".mosaic-item.is-feature img.mosaic-tilt-img--a"),
    ...document.querySelectorAll(".loader-strip-track img"),
  ];
  let loaded = 0;
  const total = Math.max(images.length, 1);
  let progress = 0;
  let target = 8;

  const tick = () => {
    progress += (target - progress) * 0.12;
    const shown = Math.min(100, Math.round(progress));
    if (loaderCount) loaderCount.textContent = String(shown).padStart(2, "0");
    if (loaderLine) loaderLine.style.transform = `scaleX(${shown / 100})`;
    if (shown < 100) requestAnimationFrame(tick);
    else finishLoader();
  };

  const bump = () => {
    loaded += 1;
    target = 12 + Math.round((loaded / total) * 88);
  };

  images.forEach((img) => {
    if (img.complete && img.naturalWidth) bump();
    else {
      img.addEventListener("load", bump, { once: true });
      img.addEventListener("error", bump, { once: true });
    }
  });

  window.setTimeout(() => {
    target = Math.max(target, 100);
  }, isMobileUi ? 2000 : 2200);

  requestAnimationFrame(tick);
};

