/* ——— Work cover tilt (TiltedCard-style, vanilla) ——— */
const MOSAIC_TILT = {
  rotateAmplitude: 4.5,
  scaleOnHover: 1.022,
  spring: 0.075,
};
let mosaicTiltCleanups = [];

const initMosaicTilt = () => {
  mosaicTiltCleanups.forEach((fn) => fn());
  mosaicTiltCleanups = [];
  if (!mosaic || reduceMotion || !finePointer) return;

  mosaic.querySelectorAll(".mosaic-tilt").forEach((figure) => {
    const inner = figure.querySelector(".mosaic-tilt-inner");
    const glare = figure.querySelector(".mosaic-tilt-glare");
    if (!inner) return;

    let raf = 0;
    let hovering = false;
    const state = { rx: 0, ry: 0, scale: 1, gx: 50, gy: 50 };
    const target = { rx: 0, ry: 0, scale: 1, gx: 50, gy: 50 };

    const paint = () => {
      raf = 0;
      const s = MOSAIC_TILT.spring;
      state.rx += (target.rx - state.rx) * s;
      state.ry += (target.ry - state.ry) * s;
      state.scale += (target.scale - state.scale) * s;
      state.gx += (target.gx - state.gx) * s;
      state.gy += (target.gy - state.gy) * s;

      const parallax = hovering ? "0px" : inner.style.getPropertyValue("--parallax-y") || "0px";
      inner.style.transform = `translate3d(0, ${parallax}, 0) rotateX(${state.rx.toFixed(3)}deg) rotateY(${state.ry.toFixed(3)}deg) scale(${state.scale.toFixed(4)})`;

      if (glare) {
        glare.style.setProperty("--glare-x", `${state.gx.toFixed(2)}%`);
        glare.style.setProperty("--glare-y", `${state.gy.toFixed(2)}%`);
      }

      const settling =
        Math.abs(target.rx - state.rx) > 0.015 ||
        Math.abs(target.ry - state.ry) > 0.015 ||
        Math.abs(target.scale - state.scale) > 0.0008 ||
        Math.abs(target.gx - state.gx) > 0.05 ||
        Math.abs(target.gy - state.gy) > 0.05;
      if (hovering || settling) raf = requestAnimationFrame(paint);
    };

    const queue = () => {
      if (!raf) raf = requestAnimationFrame(paint);
    };

    const onMove = (e) => {
      if (layoutMode !== "grid" || activeView !== "work") return;
      const rect = figure.getBoundingClientRect();
      if (rect.width < 1 || rect.height < 1) return;
      const offsetX = e.clientX - rect.left - rect.width / 2;
      const offsetY = e.clientY - rect.top - rect.height / 2;
      target.rx = (offsetY / (rect.height / 2)) * -MOSAIC_TILT.rotateAmplitude;
      target.ry = (offsetX / (rect.width / 2)) * MOSAIC_TILT.rotateAmplitude;
      target.gx = ((e.clientX - rect.left) / rect.width) * 100;
      target.gy = ((e.clientY - rect.top) / rect.height) * 100;
      queue();
    };

    const onEnter = () => {
      if (layoutMode !== "grid" || activeView !== "work") return;
      hovering = true;
      figure.classList.add("is-tilting");
      figure.closest(".mosaic-item")?.classList.add("is-tilt-active");
      target.scale = MOSAIC_TILT.scaleOnHover;
      inner.style.setProperty("--parallax-y", "0px");
      queue();
    };

    const onLeave = () => {
      hovering = false;
      figure.classList.remove("is-tilting");
      figure.closest(".mosaic-item")?.classList.remove("is-tilt-active");
      target.rx = 0;
      target.ry = 0;
      target.scale = 1;
      queue();
      requestMosaicParallax();
    };

    figure.addEventListener("pointermove", onMove, { passive: true });
    figure.addEventListener("pointerenter", onEnter);
    figure.addEventListener("pointerleave", onLeave);

    mosaicTiltCleanups.push(() => {
      figure.removeEventListener("pointermove", onMove);
      figure.removeEventListener("pointerenter", onEnter);
      figure.removeEventListener("pointerleave", onLeave);
      if (raf) cancelAnimationFrame(raf);
      figure.classList.remove("is-tilting");
      figure.closest(".mosaic-item")?.classList.remove("is-tilt-active");
      inner.style.transform = "";
    });
  });
};

