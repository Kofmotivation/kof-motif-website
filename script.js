const skipAboutFilmToEnd = () => {
  if (!aboutFilmReady || reduceMotion) return;
  if (aboutFilmProgress >= 0.995) {
    applyAboutFilmProgress(1, { syncScroll: true });
    return;
  }

  stopAboutFilmSkip();
  aboutFilmFast?.classList.add("is-active");

  const from = aboutFilmProgress;
  const start = performance.now();
  const easeOutCubic = (t) => 1 - (1 - t) ** 3;

  const tick = (now) => {
    const t = Math.min(1, (now - start) / ABOUT_FILM_SKIP_MS);
    applyAboutFilmProgress(from + (1 - from) * easeOutCubic(t), { syncScroll: true });
    if (t < 1) {
      aboutFilmFastRaf = requestAnimationFrame(tick);
      return;
    }
    aboutFilmFastRaf = 0;
    applyAboutFilmProgress(1, { syncScroll: true });
    aboutFilmFast?.classList.remove("is-active");
  };

  aboutFilmFastRaf = requestAnimationFrame(tick);
};

