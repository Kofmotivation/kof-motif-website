const openFocus = (collectionIndex, stillIndex = 0) => {
  activeCollection = (collectionIndex + COLLECTIONS.length) % COLLECTIONS.length;
  const c = COLLECTIONS[activeCollection];
  if (!c) return;
  snapCursor();
  window.setTimeout(() => openFocusSet(c.images, stillIndex, c.title), 160);
};

const closeFocus = () => {
  stopFocusSlideshow();
  focusEl?.classList.remove("is-open", "is-playing", "is-paused");
  focusEl?.setAttribute("aria-hidden", "true");
  document.body.classList.remove("focus-open");
  if (focusImg) {
    focusImg.classList.remove("is-shown", "is-exit-next", "is-exit-prev", "is-enter-next", "is-enter-prev");
    focusImg.src = PLACEHOLDER;
    focusImg.alt = "";
  }
  if (focusCaption) focusCaption.textContent = "";
  if (focusMeta) focusMeta.textContent = "";
  if (focusRail) focusRail.innerHTML = "";
  focusStills = [];
  if (!menu?.classList.contains("is-open") && !infoPanel?.classList.contains("is-open")) {
    startLocoScroll();
  }
  requestMosaicParallax();
};

const stepFocusByScroll = (delta) => {
  if (!focusEl?.classList.contains("is-open") || focusWheelLock || focusStills.length < 2) return;
  focusWheelLock = true;
  showFocusStill(focusIndex + (delta > 0 ? 1 : -1), { direction: delta > 0 ? "next" : "prev" });
  window.setTimeout(() => {
    focusWheelLock = false;
  }, reduceMotion ? 120 : 520);
};

focusEl?.addEventListener(
  "wheel",
  (e) => {
    if (!focusEl.classList.contains("is-open")) return;
    if (e.target.closest(".focus-rail, .focus-theme, .focus-back")) return;
    e.preventDefault();
    if (Math.abs(e.deltaY) < 8 && Math.abs(e.deltaX) < 8) return;
    const delta = Math.abs(e.deltaY) >= Math.abs(e.deltaX) ? e.deltaY : e.deltaX;
    stepFocusByScroll(delta);
  },
  { passive: false }
);

focusEl?.addEventListener(
  "touchstart",
  (e) => {
    if (e.target.closest(".focus-rail, .focus-theme, .focus-back")) {
      focusTouchY = null;
      return;
    }
    focusTouchY = e.touches[0]?.clientY ?? null;
  },
  { passive: true }
);

focusEl?.addEventListener(
  "touchend",
  (e) => {
    if (focusTouchY == null) return;
    const endY = e.changedTouches[0]?.clientY ?? focusTouchY;
    const dy = focusTouchY - endY;
    focusTouchY = null;
    if (Math.abs(dy) < 48) return;
    stepFocusByScroll(dy);
  },
  { passive: true }
);

