/* ——— Cursor ——— */
const snapCursor = () => {
  if (!cursor || !document.body.classList.contains("has-cursor")) return;
  cursor.classList.remove("is-snap");
  // force reflow so repeated snaps retrigger
  void cursor.offsetWidth;
  cursor.classList.add("is-snap");
  window.setTimeout(() => cursor.classList.remove("is-snap"), 280);
};

const setupCursor = () => {
  if (!finePointer || reduceMotion || !cursor) return;
  document.body.classList.add("has-cursor");
  let x = 0;
  let y = 0;
  let rx = 0;
  let ry = 0;

  window.addEventListener("pointermove", (e) => {
    x = e.clientX;
    y = e.clientY;
    cursor.classList.add("is-on");
  });

  const loop = () => {
    rx += (x - rx) * 0.22;
    ry += (y - ry) * 0.22;
    cursor.style.transform = `translate3d(${rx}px, ${ry}px, 0)`;
    requestAnimationFrame(loop);
  };
  requestAnimationFrame(loop);

  document.addEventListener("pointerover", (e) => {
    if (document.body.classList.contains("focus-open")) {
      cursor.classList.remove("is-hover", "is-small", "is-on");
      return;
    }
    const chrome = e.target.closest(".view-toggle, .view-btn, .menu-toggle, .menu-close");
    if (chrome) {
      cursor.classList.add("is-small");
      cursor.classList.remove("is-hover");
      if (cursorLabel) cursorLabel.textContent = "";
      return;
    }
    const hit = e.target.closest("[data-cursor], a, button");
    if (!hit) {
      cursor.classList.remove("is-hover", "is-small");
      if (cursorLabel) cursorLabel.textContent = "";
      return;
    }
    cursor.classList.remove("is-small");
    cursor.classList.add("is-hover");
    if (cursorLabel) cursorLabel.textContent = hit.dataset.cursor || "";
  });
};

/* ——— Keyboard ——— */
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") {
    if (shopDrawer?.classList.contains("is-open")) closeShopDrawer();
    else if (focusEl?.classList.contains("is-open")) closeFocus();
    else if (infoPanel?.classList.contains("is-open")) closeInfo();
    else if (menu?.classList.contains("is-open")) closeMenu();
  }
  if (!focusEl?.classList.contains("is-open")) return;
  if (e.key === "ArrowLeft" || e.key === "ArrowUp") showFocusStill(focusIndex - 1, { direction: "prev" });
  if (e.key === "ArrowRight" || e.key === "ArrowDown") showFocusStill(focusIndex + 1, { direction: "next" });
});

